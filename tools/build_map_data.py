def load(name):
    return json.loads((OSM / name).read_text(encoding="utf-8"))

def events():
    return json.loads((ROOT / "data" / "events.json").read_text(encoding="utf-8"))["events"]

def ids_for(rx, evs):
    """События по ключевому слову. Если в записи названы посёлки района (Маго, Красное...)
    и не назван Николаевск - это не про городскую точку, пропускаем."""
    r = re.compile(rx, re.I)
    return [e["id"] for e in evs
            if r.search(e["text"]) and (not e["places"] or "Николаевск" in e["places"])]

def main():
    evs = events()
    ways = load("osm_streets.json")["elements"]
    by_name = defaultdict(list)
    for w in ways:
        g = [[round(p["lat"], 5), round(p["lon"], 5)] for p in w.get("geometry", [])]
        if len(g) > 1:
            by_name[w["tags"]["name"]].append(g)

    streets = []
    for name, lines in sorted(by_name.items()):
        cfg = STREETS.get(name)
        item = {"name": name, "lines": lines}
        if cfg:
            rx, folder, n, note = cfg
            item.update({"events": ids_for(rx, evs), "archive": n, "folder": folder, "note": note, "hl": True})
        streets.append(item)

    pois_src = {}
    for e in load("osm_poi.json")["elements"]:
        c = e.get("center") or e
        pois_src.setdefault(e["tags"]["name"], (round(c["lat"], 5), round(c["lon"], 5)))
    pois = []
    for osm_name, title, text, rx, folder, n in POIS:
        if osm_name not in pois_src:
            print("нет в OSM:", osm_name)
            continue
        lat, lon = pois_src[osm_name]
        pois.append({"title": title, "text": text, "lat": lat, "lon": lon,
                     "events": ids_for(rx, evs), "archive": n, "folder": folder})

    places = {}
    for e in load("osm_places.json")["elements"]:
        places.setdefault(e["tags"]["name"], (round(e["lat"], 5), round(e["lon"], 5)))
    settlements = []
    for osm_name, key, folder, n in SETTLEMENTS:
        if osm_name not in places:
            print("нет в OSM:", osm_name)
            continue
        lat, lon = places[osm_name]
        ids = [e["id"] for e in evs if key in e["places"]]
        settlements.append({"title": osm_name, "lat": lat, "lon": lon, "events": ids, "archive": n, "folder": folder})

    out = {"center": [53.139, 140.717], "streets": streets, "pois": pois, "settlements": settlements,
           "attribution": "Карта и улицы © участники OpenStreetMap"}
    path = ROOT / "data" / "map.js"
    path.write_text("window.MAP_DATA=" + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";", encoding="utf-8")
    hl = [s for s in streets if s.get("hl")]
    print(f"улиц: {len(streets)} (выделено {len(hl)}), объектов: {len(pois)} -> {path} ({path.stat().st_size//1024} КБ)")
    for s in hl:
        print(f"  {s['name']}: событий {len(s['events'])}, фото в архиве {s['archive']}")
    for p in pois:
        print(f"  {p['title']}: событий {len(p['events'])}")
    print("посёлки:", ", ".join(f"{x['title']} ({len(x['events'])})" for x in settlements))

if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
