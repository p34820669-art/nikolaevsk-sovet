def resolve(ch):
    """Превращает описание главы (с find) в данные для сайта, привязывая записи по тексту."""
    c = dict(ch)
    c["timeline"] = [{"year": y, "id": eid(f, y), "title": t} for y, f, t in ch["timeline"]]
    c["compare"] = [dict(cp, id=eid(cp["find"])) for cp in ch["compare"]]
    for cp in c["compare"]:
        cp.pop("find")
    st = dict(ch["stack"])
    st["id"] = eid(st.pop("find"))
    c["stack"] = st
    c["people"] = [dict(p, id=eid(p["find"], p.get("year"))) for p in ch["people"]]   # year - необязательное уточнение года записи
    c["quiz"] = [dict(q, id=eid(q["find"], q.get("year"))) for q in ch["quiz"]]
    for group in ("people", "quiz"):
        for item in c[group]:
            item.pop("find")
            item.pop("year", None)
    c.setdefault("mapLinks", [])
    return c

def write_check_table(ch, c):
    titled = {t["id"]: t["title"] for t in c["timeline"] if t["id"]}
    path = ROOT / "data" / f"vychitka_{ch['slug']}.csv"
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["id", "год", "в главе?", "заголовок", "начало записи", "ИСТОЧНИК (заполнить)", "проверено (да/нет)", "замечание"])
        for e in EVENTS:
            if ch["from"] <= e["year"] <= ch["to"]:
                w.writerow([e["id"], e["year"], "да" if e["id"] in titled else "", titled.get(e["id"], ""), e["text"][:140], "", "", ""])

