def eid(find, year=None):
    rx = re.compile(find, re.S)
    hits = [e for e in EVENTS if rx.search(e["text"]) and (year is None or e["year"] == year)]
    if len(hits) != 1:
        BAD.append(f"find={find!r} year={year}: найдено {len(hits)}")
        return None
    return hits[0]["id"]

